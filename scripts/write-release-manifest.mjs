// Writes the two manifests a release needs:
//
//   latest.yml   — human-facing: the current version, and the installer URL,
//                  size and sha256 for each platform. Read by the novasuite
//                  download page.
//   latest.json  — machine-facing: the endpoint tauri-plugin-updater polls. Only
//                  written when signed updater artifacts are present, because an
//                  entry without its signature is one the app must reject anyway.
//
// They point at different files: a person downloads the .dmg, while the updater
// downloads the .app.tar.gz it can unpack over the installed bundle.
//
// Usage:
//   node scripts/write-release-manifest.mjs <installer-dir> [out-file]
//
// Env:
//   TAG                release tag, e.g. v0.1.0 (default: derived from file names)
//   RELEASE_BASE_URL   public prefix the installers are served from (default: the
//                      GitHub release download URL built from GITHUB_REPOSITORY)
//   GITHUB_REPOSITORY  owner/repo, set by Actions
//   RELEASED_AT        ISO timestamp (default: now)
//
// Each manifest describes exactly one version, so a bad release is rolled back
// by rewriting the file, not by editing a list.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/write-release-manifest.mjs <installer-dir> [out-file]");
  process.exit(1);
}
const out = process.argv[3] ?? join(dir, "latest.yml");

// Derived from what was actually built, so a platform that stops shipping
// simply stops appearing.
const PLATFORMS = [
  { re: /_universal\.dmg$/i, key: "darwin-universal", kind: "dmg" },
  { re: /_aarch64\.dmg$/i, key: "darwin-aarch64", kind: "dmg" },
  { re: /_x64\.dmg$/i, key: "darwin-x86_64", kind: "dmg" },
  { re: /_x64-setup\.exe$/i, key: "windows-x86_64", kind: "nsis" },
  { re: /_arm64-setup\.exe$/i, key: "windows-aarch64", kind: "nsis" },
  { re: /_x64(_[a-z]{2}-[A-Z]{2})?\.msi$/, key: "windows-x86_64-msi", kind: "msi" },
];

// Keys are the platform identifiers tauri-plugin-updater looks itself up by.
// A universal app reports darwin-aarch64 or darwin-x86_64 depending on the Mac,
// so the universal bundle is offered under both.
const UPDATER_PLATFORMS = [
  { re: /_universal\.app\.tar\.gz$/i, keys: ["darwin-universal", "darwin-aarch64", "darwin-x86_64"] },
  { re: /_aarch64\.app\.tar\.gz$/i, keys: ["darwin-aarch64"] },
  { re: /_x64\.app\.tar\.gz$/i, keys: ["darwin-x86_64"] },
  { re: /_x64-setup\.exe$/i, keys: ["windows-x86_64"] },
  { re: /_arm64-setup\.exe$/i, keys: ["windows-aarch64"] },
];

const all = readdirSync(dir).filter((f) => statSync(join(dir, f)).isFile());
const installers = all.filter((f) => /\.(dmg|exe|msi)$/i.test(f)).sort();
if (installers.length === 0) {
  console.error(`no installers found in ${dir}`);
  process.exit(1);
}

const sha256 = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");

const entries = [];
for (const file of installers) {
  const match = PLATFORMS.find((p) => p.re.test(file));
  if (!match) {
    console.warn(`::warning::unrecognised installer name, not in manifest: ${file}`);
    continue;
  }
  const path = join(dir, file);
  entries.push({ key: match.key, kind: match.kind, file, size: statSync(path).size, sha256: sha256(path) });
}

const fromName = entries.map((e) => e.file.match(/_(\d+\.\d+\.\d+)_/)?.[1]).find(Boolean);
const tag = process.env.TAG || (fromName ? `v${fromName}` : "");
const version = tag.replace(/^v/, "");
if (!version) {
  console.error("could not determine version: pass TAG=vX.Y.Z");
  process.exit(1);
}

const repo = process.env.GITHUB_REPOSITORY;
const base = (
  process.env.RELEASE_BASE_URL || (repo ? `https://github.com/${repo}/releases/download/${tag}` : "")
).replace(/\/+$/, "");
if (!base) {
  console.error("could not determine a download base: set RELEASE_BASE_URL");
  process.exit(1);
}

const releasedAt = process.env.RELEASED_AT || new Date().toISOString();
const notes = repo ? `https://github.com/${repo}/releases/tag/${tag}` : "";
const url = (file) => `${base}/${encodeURIComponent(file)}`;

// Hand-rolled YAML: the shape is fixed and shallow. Values are quoted; keys are
// known-safe identifiers.
const q = (s) => `"${String(s).replace(/(["\\])/g, "\\$1")}"`;
const lines = [
  "# Generated by scripts/write-release-manifest.mjs. Do not edit by hand.",
  `version: ${q(version)}`,
  `tag: ${q(tag)}`,
  `releasedAt: ${q(releasedAt)}`,
];
if (notes) lines.push(`notes: ${q(notes)}`);
lines.push("platforms:");
for (const e of entries) {
  lines.push(
    `  ${e.key}:`,
    `    kind: ${q(e.kind)}`,
    `    file: ${q(e.file)}`,
    `    url: ${q(url(e.file))}`,
    `    size: ${e.size}`,
    `    sha256: ${q(e.sha256)}`,
  );
}
const yaml = lines.join("\n") + "\n";
writeFileSync(out, yaml);
console.log(yaml);
console.log(`wrote ${out} (${entries.length} platform(s))`);

// An updater entry needs the detached signature the bundler writes next to the
// artifact as <artifact>.sig when TAURI_SIGNING_PRIVATE_KEY is set. Without one
// the app would refuse the update, so the platform is skipped.
const updater = {};
for (const file of all.sort()) {
  const match = UPDATER_PLATFORMS.find((p) => p.re.test(file));
  if (!match) continue;
  let signature;
  try {
    signature = readFileSync(join(dir, `${file}.sig`), "utf8").trim();
  } catch {
    console.warn(`::warning::no signature for ${file}, not offered to the updater`);
    continue;
  }
  for (const key of match.keys) updater[key] ??= { signature, url: url(file) };
}

const updaterOut = join(dirname(out), "latest.json");
if (Object.keys(updater).length === 0) {
  // Not an error: an unsigned build is valid, it just cannot be an update
  // source. Writing nothing keeps the previous latest.json in place.
  console.warn("::warning::no signed updater artifacts, latest.json not written");
} else {
  const json = {
    version,
    notes: notes || `NovaPDF ${version}`,
    pub_date: releasedAt,
    platforms: updater,
  };
  writeFileSync(updaterOut, JSON.stringify(json, null, 2) + "\n");
  console.log(`wrote ${updaterOut} (${Object.keys(updater).join(", ")})`);
}
